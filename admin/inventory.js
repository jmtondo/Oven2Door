    document.getElementById(
        "modalCurrentStock"
    );

const quantityDisplay =
    document.getElementById(
        "quantityDisplay"
    );



/* =====================================================
   OPEN STOCK MODAL
===================================================== */

function openStockModal(id, type) {

    selectedProduct =
        inventory.find(product =>
            product.id === id
        );


    adjustmentType = type;


    /*
        IMPORTANT:

        The adjustment starts at 0.

        The original stock is NOT
        changed when the modal opens.
    */

    adjustmentQuantity = 0;


    quantityDisplay.textContent =
        adjustmentQuantity;


    if (type === "add") {

        modalTitle.textContent =
            "Add Stocks";

    } else {

        modalTitle.textContent =
            "Remove Stocks";

    }


    modalProductImage.src =
        selectedProduct.image;


    modalProductImage.alt =
        selectedProduct.name;


    modalProductName.textContent =
        selectedProduct.name;


    modalProductCategory.textContent =
        `${selectedProduct.categoryName} • ${selectedProduct.subcategory}`;


    modalCurrentStock.textContent =
        selectedProduct.stock;


    stockModal.classList.add("show");

    modalOverlay.classList.add("show");

}



/* =====================================================
   PLUS
===================================================== */

document
    .getElementById("plusButton")
    .addEventListener("click", () => {

        /*
            For REMOVE:
            do not allow quantity to exceed
            the current stock.
        */

        if (
            adjustmentType === "remove" &&
            adjustmentQuantity >= selectedProduct.stock
        ) {

            return;

        }


        adjustmentQuantity++;


        quantityDisplay.textContent =
            adjustmentQuantity;

    });



/* =====================================================
   MINUS
===================================================== */

document
    .getElementById("minusButton")
    .addEventListener("click", () => {

        if (adjustmentQuantity > 0) {

            adjustmentQuantity--;

        }


        quantityDisplay.textContent =
            adjustmentQuantity;

    });



/* =====================================================
   SAVE
===================================================== */

document
    .getElementById("saveButton")
    .addEventListener("click", () => {

        if (!selectedProduct) {

            return;

        }


        /*
            ADD STOCKS
        */

        if (adjustmentType === "add") {

            selectedProduct.stock +=
                adjustmentQuantity;

        }


        /*
            REMOVE STOCKS
        */

        if (adjustmentType === "remove") {

            selectedProduct.stock -=
                adjustmentQuantity;


            /*
                Never allow negative stocks.
            */

            if (selectedProduct.stock < 0) {

                selectedProduct.stock = 0;

            }

        }


        /*
            Update the table.
        */

        displayInventory();


        /*
            Close modal.
        */

        closeStockModal();

    });



/* =====================================================
   CANCEL
===================================================== */

document
    .getElementById("cancelButton")
    .addEventListener(
        "click",
        closeStockModal
    );


document
    .getElementById("closeModal")
    .addEventListener(
        "click",
        closeStockModal
    );


modalOverlay.addEventListener(
    "click",
    closeStockModal
);



/* =====================================================
   CLOSE MODAL
===================================================== */

function closeStockModal() {

    /*
        Reset temporary quantity.

        Since the actual product stock
        is only changed inside SAVE,
        cancelling automatically keeps
        the original stock.
    */

    adjustmentQuantity = 0;

    selectedProduct = null;

    stockModal.classList.remove("show");

    modalOverlay.classList.remove("show");

}



/* =====================================================
   INITIAL DISPLAY
===================================================== */

displayInventory();